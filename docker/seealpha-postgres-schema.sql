-- SeeAlpha-owned runtime tables. Separate from NautilusTrader's PostgreSQL schema.
-- Only actively used tables are created; retired SQLite/Paper/compatibility tables are not recreated.
BEGIN;
CREATE SCHEMA IF NOT EXISTS seealpha;
SET LOCAL search_path TO seealpha, public;

-- Ledger-owned immutable order safety envelope (until native execution cutover).
CREATE TABLE IF NOT EXISTS order_intents (
    account_id TEXT NOT NULL,
    request_id TEXT NOT NULL,
    environment TEXT NOT NULL,
    client_order_id TEXT NOT NULL,
    fingerprint TEXT NOT NULL,
    intent_json TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (account_id, request_id)
);
CREATE TABLE IF NOT EXISTS order_observations (
    account_id TEXT NOT NULL,
    environment TEXT NOT NULL,
    client_order_id TEXT NOT NULL,
    observation_id TEXT NOT NULL,
    observed_at_ns BIGINT NOT NULL,
    status TEXT NOT NULL,
    evidence_json TEXT NOT NULL,
    PRIMARY KEY(account_id,environment,client_order_id,observation_id)
);
CREATE TABLE IF NOT EXISTS account_evidence_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    account_id TEXT NOT NULL,
    environment TEXT NOT NULL,
    kind TEXT NOT NULL,
    evidence_id TEXT NOT NULL,
    evidence_json TEXT NOT NULL,
    recorded_at_ms BIGINT NOT NULL,
    UNIQUE(account_id,environment,kind,evidence_id)
);
-- Strategy attribution of immutable, verified account evidence.
-- No balance/position cache and no synthetic exchange fills.
CREATE TABLE IF NOT EXISTS account_event_allocations (
    account_id TEXT NOT NULL,
    environment TEXT NOT NULL CHECK(environment IN ('production','sandbox')),
    event_id BIGINT NOT NULL REFERENCES account_evidence_events(id),
    strategy_id TEXT NOT NULL,
    basis_points BIGINT NOT NULL CHECK(basis_points BETWEEN 1 AND 10000),
    recorded_at_ms BIGINT NOT NULL,
    PRIMARY KEY (account_id,environment,event_id,strategy_id)
);

CREATE TABLE IF NOT EXISTS orders (
    account_id TEXT NOT NULL,
    environment TEXT NOT NULL,
    client_order_id TEXT NOT NULL,
    order_json TEXT NOT NULL,
    updated_at BIGINT NOT NULL,
    PRIMARY KEY (account_id, environment, client_order_id)
);
CREATE TABLE IF NOT EXISTS fills (
    account_id TEXT NOT NULL,
    environment TEXT NOT NULL,
    fill_id TEXT NOT NULL,
    fill_json TEXT NOT NULL,
    updated_at BIGINT NOT NULL,
    PRIMARY KEY (account_id, environment, fill_id)
);
CREATE TABLE IF NOT EXISTS account_settlements (
    account_id TEXT NOT NULL,
    environment TEXT NOT NULL,
    product TEXT NOT NULL,
    event_kind TEXT NOT NULL,
    event_id TEXT NOT NULL,
    symbol TEXT NOT NULL,
    evidence_json TEXT NOT NULL,
    PRIMARY KEY(account_id,environment,product,event_kind,event_id)
);

CREATE INDEX IF NOT EXISTS order_intents_client
    ON order_intents(account_id, environment, client_order_id);
CREATE INDEX IF NOT EXISTS order_observations_by_time
    ON order_observations(account_id,environment,client_order_id,observed_at_ns);
CREATE INDEX IF NOT EXISTS account_evidence_events_page
    ON account_evidence_events(account_id,environment,id);
CREATE INDEX IF NOT EXISTS account_event_allocations_by_evidence
    ON account_event_allocations(account_id,environment,event_id);
CREATE INDEX IF NOT EXISTS account_settlement_symbol
    ON account_settlements(account_id,environment,product,symbol);

-- Pipeline desired state. One row per product/instrument.
CREATE TABLE IF NOT EXISTS pipeline_subscriptions (
 product TEXT NOT NULL CHECK(product IN ('spot','futures_um','options')),
 symbol TEXT NOT NULL, history_start TEXT NOT NULL,
 realtime_enabled BOOLEAN NOT NULL DEFAULT FALSE,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 price_precision INTEGER, size_precision INTEGER, updated_at BIGINT NOT NULL,
 PRIMARY KEY(product,symbol)
);

-- Source: engine/strategy/src/store.rs
CREATE TABLE IF NOT EXISTS strategy_issuances (
 account_id TEXT NOT NULL, issuance_id TEXT NOT NULL,
 code_key TEXT NOT NULL, version TEXT NOT NULL,
 parameters_json TEXT NOT NULL, entry_point TEXT NOT NULL,
 package_hash TEXT NOT NULL, zip_sha256 TEXT,
 PRIMARY KEY (account_id,issuance_id)
);
CREATE INDEX IF NOT EXISTS strategy_name_version ON strategy_issuances (code_key,version);

COMMIT;
